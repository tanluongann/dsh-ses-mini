/**
 * The mail layer: raw MIME in, raw MIME out — pure functions, no AWS, no DSH.
 *
 * Split out of `ses.js` on purpose: everything that decides *what a message means* and
 * *what an answer looks like* lives here and is exercised by `test/harness.mjs` against
 * fixture `.eml` files. The transport (S3/SES) is a thin adapter over this.
 *
 * Two rules shape every function below:
 *   1. a mail loop must be impossible — see `automationReason`;
 *   2. content must never be silently lost — a body we cannot parse is reported, not
 *      dropped, and quote-stripping has to be conservative enough that an inline answer
 *      survives it (see `splitQuote`).
 */
import { randomUUID } from 'node:crypto'
import { simpleParser } from 'mailparser'
import { normaliseAddress } from './config.js'

/** Echoed subjects are cut here: the reply echoes the original, it does not own it. */
const SUBJECT_ECHO_CAP = 500
/** Header lines we still consider foldable/finite (SMTP hard limit is 998 octets). */
const HEADER_FOLD_AT = 78

/**
 * Lowercased raw headers, unfolded.
 *
 * Deliberately read from `headerLines` rather than mailparser's `headers` Map: that Map is
 * *interpreted*, and interpretation hides exactly the headers the loop guards need —
 * `List-Id: <x.example.com>` arrives as `headers.get('list')`, and `headers.get('list-id')`
 * is `undefined`. A guard written against the parsed shape silently stops guarding.
 *
 * @returns {Map<string,string>} name → value, both lowercased/unfolded
 */
export function rawHeaders(parsed) {
  const out = new Map()
  for (const entry of parsed?.headerLines ?? []) {
    const key = String(entry?.key ?? '').toLowerCase()
    if (key === '') continue
    // A folded header keeps its CRLF + whitespace inside `line`; unfold to one line.
    out.set(key, String(entry?.line ?? '').replace(/[^\S\r\n]*[\r\n]+\s*/g, ' ').trim())
  }
  return out
}

/** The value of a raw header, without its name. */
export function headerValue(headers, name) {
  const line = headers.get(String(name).toLowerCase())
  if (line === undefined) return undefined
  const colon = line.indexOf(':')
  return (colon === -1 ? line : line.slice(colon + 1)).trim()
}

/**
 * Why this message must not start a turn, or `undefined` if it may.
 *
 * Every entry here exists because the corresponding construct *will* mail us back if we
 * answer it: an out-of-office reply answers our answer, a list explodes a reply to every
 * member, a bounce of our own answer carries `Return-Path: <>`. The returned string is the
 * reason written to the log, so it names the header that matched — "refused" without a
 * reason is what makes a mail problem take an afternoon to find.
 *
 * @param {Map<string,string>} headers raw headers (see {@link rawHeaders})
 * @param {string} subject decoded subject, for the headerless-autoresponder fallback
 */
export function automationReason(headers, subject = '') {
  const value = (name) => (headerValue(headers, name) ?? '').trim()

  // RFC 3834. `no` is the only value that means "a human typed this".
  const autoSubmitted = value('auto-submitted')
  if (autoSubmitted !== '' && autoSubmitted.toLowerCase() !== 'no') {
    return `auto-submitted: ${autoSubmitted.slice(0, 40)}`
  }
  // The bulk markers from RFC 2076/2919-era mailers and every newsletter platform.
  const precedence = value('precedence').toLowerCase()
  if (['bulk', 'junk', 'list'].includes(precedence)) return `precedence: ${precedence}`
  // Mailing lists: List-Id is the deliberate trap (see rawHeaders), the rest are belt and braces.
  for (const name of ['list-id', 'list-post', 'list-subscribe', 'list-unsubscribe', 'list-help', 'x-mailing-list']) {
    const listValue = value(name)
    if (listValue !== '') return `${name}: ${listValue.slice(0, 40)}`
  }
  // Autoresponders whose author never read RFC 3834. `X-Auto-Response-Suppress` is what
  // Exchange puts on *outgoing* auto-replies; the others are older Outlook/Notes markers.
  for (const name of ['x-autoreply', 'x-autorespond', 'x-autoresponse', 'x-auto-response-suppress', 'x-autogenerated']) {
    const marker = value(name)
    if (marker !== '') return `${name}: ${marker.slice(0, 40)}`
  }
  // A null envelope sender is a bounce (or a vacation reply) by definition: there is no
  // mailbox to answer, and answering a bounce is how loops start.
  if (headers.has('return-path') && value('return-path').replace(/[<>]/g, '') === '') return 'null return path (bounce)'
  // Last resort, for the mailers that set no header at all: the subject is the only tell.
  const subjectHead = String(subject ?? '').trim().toLowerCase()
  if (/^(auto(matic)?[- ]?(reply|response)|out of (the )?office|r[ée]ponse automatique|abwesenheit|respuesta autom[áa]tica|auto)\s*[:\]]/.test(subjectHead)) {
    return `subject looks automated: ${subjectHead.slice(0, 40)}`
  }
  return undefined
}

/**
 * Split a body into the part the human wrote and the history they quoted.
 *
 * This is the risky function in the file, and it is written the paranoid way on purpose:
 * a channel that trims too eagerly loses the answer, which is worse than carrying a quote.
 * So there are exactly two cuts, and both refuse when the message might be *inline*:
 *
 *   1. a recognised separator (`On … wrote:`, `-----Original Message-----`, Outlook's
 *      `________`) — unless anything below it is not quoted, which is the signature of a
 *      bottom-posted reply whose words come *after* the quote;
 *   2. a bare `>` run at the very END of the message.
 *
 * A top-posted Gmail/Outlook reply is cut by (1); an inline reply (`> q` … answer … `> q`)
 * matches neither and is passed through whole.
 *
 * @returns {{ body: string, quote: string, inline: boolean }}
 */
/**
 * SES's own authentication verdict for a message, or `undefined` when there is none.
 *
 * An allowlist keyed on `From:` is spoofable: anyone can write the owner's address in the
 * header, and SES will still accept the mail as long as SPF/DKIM pass for whatever domain
 * actually sent it. `dmarc=pass` is the verdict that closes that hole — it means SPF *or*
 * DKIM aligned with the header domain, which is exactly the claim an impersonator cannot
 * make. The verdict is also logged for every accepted message, so "why did she believe
 * this?" is answerable after the fact.
 *
 * Only the FIRST `Authentication-Results` whose authserv-id is `amazonses.com` is read, and
 * it is read from the raw header lines in wire order rather than from the header Map: SES
 * *prepends* its additions, so a forged header would sit later in the message, while the Map
 * keeps the last one — i.e. the forged one. (RFC 8601 says not to trust these headers from
 * untrusted sources at all; taking the first SES-authored one is the closest a receiver gets.)
 *
 * @param {Array<{key: string, line: string}>} headerLines mailparser's raw header lines
 */
export function authentication(headerLines = []) {
  for (const entry of headerLines) {
    if (String(entry?.key ?? '').toLowerCase() !== 'authentication-results') continue
    const line = String(entry?.line ?? '').replace(/[^\S\r\n]*[\r\n]+\s*/g, ' ').trim()
    const colon = line.indexOf(':')
    const value = (colon === -1 ? line : line.slice(colon + 1)).trim()
    if (!/^amazonses\.com\b/i.test(value)) continue
    const pick = (name) => {
      const match = new RegExp(`${name}=(\\w+)`).exec(value)
      return match === null ? undefined : match[1].toLowerCase()
    }
    const from = /dmarc=\w+\s+header\.from=([^\s;]+)/i.exec(value)
    // DKIM results each carry the signing domain: `dkim=pass header.i=@example.com`. Only a
    // pass whose domain matches the From domain proves anything about the From header, so the
    // aligned ones are collected separately from the bare result.
    const dkimDomains = [...value.matchAll(/dkim=pass\s+header\.i=@([^\s;]+)/gi)].map((m) => m[1].toLowerCase())
    return {
      spf: pick('spf'),
      dkim: pick('dkim'),
      dmarc: pick('dmarc'),
      /** The domain DMARC was evaluated for — the address the verdict actually covers. */
      dmarcFrom: from === null ? undefined : from[1].toLowerCase(),
      /** Domains with a passing, aligned DKIM signature. */
      dkimDomains,
      raw: value.slice(0, 300),
    }
  }
  return undefined
}

/**
 * Is the From header backed by SES's verdict?
 *
 * `dmarc` accepts only `dmarc=pass`. `aligned` also accepts a DKIM pass whose signing domain is
 * the From domain — the same proof (only the real domain holds the key) for domains that publish
 * SPF and DKIM but no DMARC record, which is common on small business domains. Both refuse a
 * forged From; `aligned` simply refuses fewer legitimate ones.
 *
 * @param {'off'|'dmarc'|'aligned'} mode
 * @param {{dmarc?: string, dkimDomains?: string[]}} [auth]
 * @param {string} from the sender address
 */
export function senderAuthenticated(mode, auth, from) {
  if (mode === 'off') return true
  if (auth === undefined) return false
  if (auth.dmarc === 'pass') return true
  if (mode === 'dmarc') return false
  const domain = String(from ?? '').split('@')[1]?.toLowerCase() ?? ''
  return domain !== '' && (auth.dkimDomains ?? []).includes(domain)
}

/** One-line summary of a verdict, for the inbound log line. */
export function authSummary(auth) {
  if (auth === undefined) return 'auth=none'
  return `auth dmarc=${auth.dmarc ?? '?'} spf=${auth.spf ?? '?'} dkim=${auth.dkim ?? '?'}` +
    (auth.dmarcFrom === undefined ? '' : ` from=${auth.dmarcFrom}`)
}

export function splitQuote(text) {
  const source = String(text ?? '').replace(/\r\n/g, '\n')
  const lines = source.split('\n')

  const separator = (line) => {
    if (/^\s*-{2,}\s*(original|reply|forwarded)\s+message\s*-{2,}\s*$/i.test(line)) return true
    if (/^\s*_{5,}\s*$/.test(line)) return true
    if (/^\s*-{5,}\s*$/.test(line)) return true
    // `On <date>, <name> wrote:` / `Le … a écrit :` / `Am … schrieb …:` / `El … escribió:`
    if (/^\s*(on|le|am|el)\b.{0,240}\b(wrote|a écrit|écrit|schrieb|escribi[óo])\b.{0,20}:\s*$/i.test(line)) return true
    return false
  }

  const isQuoted = (line) => /^\s*>/.test(line)

  /**
   * Lines below a separator that a human might have written.
   *
   * The embedded-message header that Outlook puts under its `________` ruler
   * (`From:` / `Sent:` / `To:` / `Subject:`) belongs to the QUOTE, not to the reply, so it is
   * stepped over before the test — but only when it really looks like one (two or more known
   * header names). A single `Name: something` line is far more likely to be prose, and
   * treating prose as a header block would cut the answer away.
   */
  const strays = (tail) => {
    const KNOWN = new Set(['from', 'sent', 'to', 'cc', 'bcc', 'subject', 'date', 'reply-to', 'importance'])
    let index = 0
    while (index < tail.length && tail[index].trim() === '') index += 1
    let known = 0
    while (index < tail.length && /^[A-Za-z][A-Za-z-]{0,38}:/.test(tail[index])) {
      if (KNOWN.has(tail[index].slice(0, tail[index].indexOf(':')).trim().toLowerCase())) known += 1
      index += 1
    }
    while (index < tail.length && /^\s+\S/.test(tail[index])) index += 1 // folded continuations
    return known >= 2 ? tail.slice(index).filter((line) => line.trim() !== '' && !isQuoted(line)) : tail.filter((line) => line.trim() !== '' && !isQuoted(line))
  }

  for (let index = 0; index < lines.length; index += 1) {
    if (!separator(lines[index])) continue
    const tail = lines.slice(index + 1)
    if (strays(tail).length > 0) {
      // Bottom-posted: the human answered under the quote. Keep everything.
      return { body: source.trim(), quote: '', inline: true }
    }
    const body = lines.slice(0, index).join('\n').trim()
    if (body === '') return { body: source.trim(), quote: '', inline: false }
    return { body, quote: tail.join('\n').trim(), inline: false }
  }

  // Trailing `>` run only: never cuts an inline reply, because there the quote precedes
  // the words rather than following them.
  let start = lines.length
  let sawQuote = false
  while (start > 0) {
    const line = lines[start - 1]
    if (line.trim() === '') { start -= 1; continue }
    if (!isQuoted(line)) break
    sawQuote = true
    start -= 1
  }
  const trimmed = lines.slice(0, start).join('\n').trim()
  if (sawQuote && trimmed !== '') return { body: trimmed, quote: lines.slice(start).join('\n').trim(), inline: false }
  return { body: source.trim(), quote: '', inline: false }
}

/** Cut a body to `maxChars`, saying so, rather than handing the model a novel. */
export function clipBody(text, maxChars) {
  const source = String(text ?? '').trim()
  const cap = Number.isFinite(maxChars) && maxChars > 0 ? maxChars : 20_000
  if (source.length <= cap) return source
  return `${source.slice(0, cap)}\n\n[truncated: ${source.length - cap} more characters not shown]`
}

/** `Re: …` exactly once, whatever prefix the original already carried. */
export function replySubject(subject, cap = SUBJECT_ECHO_CAP) {
  let base = String(subject ?? '').replace(/[\r\n]+/g, ' ').trim()
  if (base.length > cap) base = `${base.slice(0, cap - 1)}…`
  if (base === '') return 'Re: (no subject)'
  return /^re\s*:/i.test(base) ? base : `Re: ${base}`
}

/**
 * Thread the reply: `In-Reply-To` is the message we are answering, `References` is the whole
 * chain that led to it.
 *
 * The chain is what makes the answer land in the original conversation in clients that
 * thread by References (and it is why a reply to a reply must not drop the root). The
 * original's own `In-Reply-To` is appended when it is not already the tail of the chain —
 * without that, a two-deep thread can lose its middle in a client that only reads the last
 * two ids.
 */
export function threadOf(mail) {
  const inReplyTo = normaliseMessageId(mail?.messageId)
  const chain = []
  for (const id of Array.isArray(mail?.references) ? mail.references : []) {
    const normalised = normaliseMessageId(id)
    if (normalised !== undefined && !chain.includes(normalised)) chain.push(normalised)
  }
  const parent = normaliseMessageId(mail?.inReplyTo)
  if (parent !== undefined && !chain.includes(parent)) chain.push(parent)
  if (inReplyTo !== undefined && !chain.includes(inReplyTo)) chain.push(inReplyTo)
  return { inReplyTo, references: chain }
}

/** `<id@host>` with exactly one pair of angle brackets, or undefined for an empty value. */
export function normaliseMessageId(value) {
  const raw = String(value ?? '').replace(/[\r\n]+/g, ' ').trim()
  if (raw === '') return undefined
  const inner = raw.replace(/^</, '').replace(/>$/, '').trim()
  return inner === '' ? undefined : `<${inner}>`
}

/** Header-safe: a newline in a value would become a second header (see {@link buildReply}). */
function oneLine(value) {
  return String(value ?? '').replace(/[^\S\r\n]*[\r\n]+\s*/g, ' ').replace(/\s{2,}/g, ' ').trim()
}

/** Non-ASCII goes out as an RFC 2047 encoded word; ASCII stays readable. */
function encodeHeaderText(value) {
  const text = oneLine(value)
  if (/^[\x20-\x7e]*$/.test(text)) return text
  return `=?UTF-8?B?${Buffer.from(text, 'utf8').toString('base64')}?=`
}

/** A display name is always quoted: `"Nelly" <a@b>` cannot be read as a group syntax. */
function formatAddress(name, address) {
  const clean = oneLine(name)
  if (clean === '') return address
  return `${encodeHeaderText(clean.replace(/"/g, ''))} <${address}>`
}

/**
 * Fold a long header at its whitespace, continuation lines starting with one space.
 *
 * Only used for values that are whitespace-separated lists (References, address lists),
 * where folding is transparent to the parser. An unbreakable value is emitted as-is.
 */
function foldHeader(name, value) {
  const head = `${name}: `
  if (head.length + value.length <= HEADER_FOLD_AT) return [`${head}${value}`]
  const words = value.split(' ')
  const lines = []
  let current = head
  for (const word of words) {
    const candidate = current === head ? `${current}${word}` : `${current} ${word}`
    if (candidate.length > HEADER_FOLD_AT && current !== head) {
      lines.push(current)
      current = ` ${word}`
      continue
    }
    current = candidate
  }
  lines.push(current)
  return lines
}

/** RFC 5322 date in UTC: unambiguous, and needs no timezone database. */
export function rfc5322Date(date = new Date()) {
  return new Date(date).toUTCString().replace(/GMT$/, '+0000')
}

/**
 * Build the raw MIME message for one answer.
 *
 * Hand-rolled, not nodemailer: three things have to be exactly right and none of them is a
 * feature — header injection, non-ASCII bodies, and the threading headers. A small builder
 * makes them testable and keeps the dependency list to the parser we actually need.
 *
 * Why base64 for the body: the text is model output. It is arbitrary UTF-8 with arbitrary
 * line lengths, and a single line over 998 octets is illegal in SMTP (relays re-wrap or
 * corrupt it). base64 removes both the charset and the line-length question at once.
 *
 * @param {object} input
 * @param {object} input.config resolved config
 * @param {object} input.mail   the inbound message being answered
 * @param {string} input.body   the answer text
 * @param {Date}   [input.now]
 * @returns {{ raw: Buffer, headers: Record<string,string>, to: string, subject: string }}
 */
export function buildReply({ config, mail, body, now = new Date() }) {
  const to = mail.from
  const subject = replySubject(mail.subject)
  const { inReplyTo, references } = threadOf(mail)
  const sender = headerOnlyAddress(config.fromAddress)
  const domain = sender.split('@')[1] ?? 'localhost'
  const messageId = `<sm-${randomUUID()}@${domain}>`

  const text = composeBody({ config, mail, body })

  const headerLines = []
  const push = (name, value) => {
    // The injection barrier. Every value below is either config-supplied or derived from
    // the original message's headers, i.e. from the internet; a CRLF smuggled inside one
    // of them would end the header block and start a new one (`Bcc:`), so every value is
    // flattened to a single line before it is written.
    if (value === undefined || value === '') return
    for (const line of foldHeader(name, encodeHeaderText(value))) headerLines.push(line)
  }
  push('From', config.fromName === '' ? sender : formatAddress(config.fromName, sender))
  push('To', mail.fromName === '' ? to : formatAddress(mail.fromName, to))
  if (oneLine(config.replyTo) !== '') push('Reply-To', headerOnlyAddress(config.replyTo))
  push('Subject', subject)
  push('Date', rfc5322Date(now))
  push('Message-ID', messageId)
  push('In-Reply-To', inReplyTo)
  push('References', references.length === 0 ? undefined : references.join(' '))
  // RFC 3834 on OUR output: if this answer is ever delivered back to this mailbox — a
  // misconfigured alias, a loop through someone's autoresponder — the inbound guard drops
  // it by this header alone. Outbound marking is what makes the loop guard airtight.
  push('Auto-Submitted', 'auto-replied')
  push('MIME-Version', '1.0')
  push('Content-Type', 'text/plain; charset=utf-8')
  push('Content-Transfer-Encoding', 'base64')

  const encoded = Buffer.from(text, 'utf8').toString('base64').replace(/(.{76})/g, '$1\r\n').replace(/\r\n$/, '')
  const raw = Buffer.from(`${headerLines.join('\r\n')}\r\n\r\n${encoded}\r\n`, 'utf8')

  return {
    raw,
    headers: unfoldHeaderLines(headerLines),
    to,
    subject,
  }
}

/**
 * `['Subject: a', 'References: <1>', ' <2>']` → `{ Subject: 'a', References: '<1> <2>' }`.
 *
 * The folded form is what goes on the wire; this is the readable one, for the log line and
 * for assertions. Rebuilding it from the first line of each header only would silently
 * truncate every folded value — which is exactly the `References` chain, i.e. the thing that
 * threads the reply.
 */
export function unfoldHeaderLines(headerLines) {
  const out = {}
  let last
  for (const line of headerLines) {
    if (/^\s/.test(line) && last !== undefined) {
      out[last] = `${out[last]} ${line.trim()}`
      continue
    }
    const colon = line.indexOf(':')
    last = line.slice(0, colon)
    out[last] = line.slice(colon + 1).trim()
  }
  return out
}

/** Answer text = the model's words, the signature, and optionally the quoted original. */
export function composeBody({ config, mail, body }) {
  const parts = [String(body ?? '').trim()]
  const signature = typeof config?.signature === 'string' ? config.signature.trim() : ''
  if (signature !== '') {
    // RFC 3676: the delimiter is `-- ` on its own line, and clients hide everything after
    // it. It is emitted only when there is a signature to hide.
    parts.push(`-- \n${signature}`)
  }
  if (config?.includeQuotedOriginal === true) {
    // The original is what the HUMAN wrote — the text the model answered — not the history
    // they quoted under it. Quoting their own quote back to them is how a reply turns into a
    // copy of the thread.
    const original = clipBody(mail?.body, config.quoteChars)
    if (original !== '') {
      const who = mail?.fromName === '' || mail?.fromName === undefined ? mail.from : `${mail.fromName} <${mail.from}>`
      const when = mail?.date instanceof Date ? mail.date.toUTCString() : 'an earlier message'
      parts.push(`On ${when}, ${who} wrote:\n${original.split('\n').map((line) => `> ${line}`).join('\n')}`)
    }
  }
  return parts.filter((part) => part !== '').join('\n\n')
}

/** The bare addr-spec, whatever the config gave us (`Nelly <a@b>` or `a@b`). */
export function headerOnlyAddress(value) {
  const raw = String(value ?? '')
  const angled = raw.match(/<([^<>]*)>/)
  return (angled === null ? raw : angled[1]).trim()
}

/**
 * The text handed to the agent for one mail.
 *
 * The envelope block is not decoration: without it the model does not know the input is
 * email, and the two failure modes of that are real — it may try to send mail itself
 * (`aws ses send-raw-email`, a bash call, a hallucinated tool), or answer as if it were in
 * a chat window with no subject. The last line tells it what this channel does with its
 * output, which is the part it cannot infer.
 */
export function userText(mail, config) {
  const who = mail.fromName === '' ? mail.from : `${mail.fromName} <${mail.from}>`
  const subject = mail.subject === '' ? '(no subject)' : mail.subject
  const envelope =
    `[email from ${who} · subject "${subject}" · ${mail.date instanceof Date ? mail.date.toUTCString() : 'unknown date'}]`
  const instruction = '[this channel emails your final answer back as a threaded reply — write the reply; do not send mail yourself]'
  return `${envelope}\n${instruction}\n\n${mail.body}`
}

/** The honest receipt for a turn that produced no answer text (a receipt is not noise). */
export function emptyAnswer(turn) {
  const kind = turn?.endReason?.kind ?? turn?.endReason ?? 'unknown'
  const message = turn?.endReason?.error?.message ?? turn?.errorLine
  return message === undefined
    ? `(no answer text was produced this turn — ended: ${kind})`
    : `(no answer text was produced this turn — ended: ${kind}: ${String(message).slice(0, 300)})`
}

/** Append a failure/abort note to an answer, so a half-finished turn is never dressed as one. */
export function answerBody(turn, config) {
  const text = String(turn?.lastText ?? '').trim()
  const kind = turn?.endReason?.kind ?? turn?.endReason
  const note = kind === 'error' || kind === 'aborted'
    ? `[this turn ended ${kind === 'error' ? 'with an error' : 'early'}${
      turn?.endReason?.error?.message === undefined ? '' : `: ${String(turn.endReason.error.message).slice(0, 300)}`
    }]`
    : ''
  if (text === '') return emptyAnswer(turn)
  return note === '' ? text : `${text}\n\n${note}`
}

/**
 * Parse one raw MIME object into the shape the bot works with.
 *
 * Identity for dedup comes from `Message-ID` when present and from the S3 key otherwise —
 * a sender is free to omit the header, and a mail that cannot be deduplicated is a mail
 * that gets answered twice.
 *
 * @param {Uint8Array|Buffer|string} raw
 * @param {{ key?: string, maxBodyChars?: number }} [options]
 */
export async function parseMail(raw, { key = '', maxBodyChars = 20_000 } = {}) {
  const parsed = await simpleParser(raw)
  const headers = rawHeaders(parsed)
  const from = normaliseAddress(parsed.from?.value?.[0]?.address ?? headerValue(headers, 'from'))
  const fromName = oneLine(parsed.from?.value?.[0]?.name ?? '')
  const messageId = normaliseMessageId(parsed.messageId)
  const text = typeof parsed.text === 'string' && parsed.text.trim() !== ''
    ? parsed.text
    : String(parsed.html ?? '').replace(/<[^>]*>/g, ' ').replace(/\s{2,}/g, ' ').trim()
  const split = splitQuote(text)
  const references = String(headerValue(headers, 'references') ?? '').split(/\s+/).filter((id) => id !== '')

  return {
    key,
    messageId,
    /** Where the dedup identity came from — an S3-key-only identity is worth seeing in the log. */
    identity: messageId === undefined ? `s3:${key}` : messageId,
    identitySource: messageId === undefined ? 's3' : 'header',
    from,
    fromName,
    subject: oneLine(parsed.subject ?? headerValue(headers, 'subject') ?? ''),
    date: parsed.date instanceof Date ? parsed.date : new Date(),
    /** The part the human wrote: what the model sees, and what a quote would quote. */
    body: clipBody(split.body, maxBodyChars),
    /** True when the message looked bottom-posted and nothing was stripped. */
    inline: split.inline,
    /** Untouched text, for the log: the difference from `body` is the stripped history. */
    plain: clipBody(text, Math.max(maxBodyChars, 4_000)),
    headers,
    /** SES's authentication verdict — see {@link authentication}. */
    auth: authentication(parsed.headerLines),
    automation: automationReason(headers, parsed.subject ?? ''),
    references,
    inReplyTo: normaliseMessageId(parsed.inReplyTo ?? headerValue(headers, 'in-reply-to')),
  }
}
